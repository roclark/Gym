@dataclass(frozen=True)
class CyberGymApptainerManifest:
    task_type: str
    vulnerable_image: str
    fixed_image: str
    auth_token: str

    @classmethod
    def load(cls, path: Path) -> "CyberGymApptainerManifest":
        if not path.is_file():
            raise FileNotFoundError(
                f"CyberGym Apptainer manifest is missing: {path}. Re-run `gym eval prepare --benchmark cybergym`."
            )
        value = json.loads(path.read_text(encoding="utf-8"))
        if value.get("schema_version") != 1:
            raise ValueError(f"Unsupported CyberGym Apptainer manifest schema in {path}")
        manifest = cls(
            task_type=str(value.get("task_type", "")),
            vulnerable_image=str(value.get("vulnerable_image", "")),
            fixed_image=str(value.get("fixed_image", "")),
            auth_token=str(value.get("auth_token", "")),
        )
        if manifest.task_type not in {"arvo", "oss-fuzz"}:
            raise ValueError(f"Invalid CyberGym task type in {path}: {manifest.task_type!r}")
        if not manifest.vulnerable_image or not manifest.fixed_image:
            raise ValueError(f"CyberGym runner image references are missing from {path}")
        if any(
            "\n" in image or image.startswith("docker://")
            for image in (manifest.vulnerable_image, manifest.fixed_image)
        ):
            raise ValueError(f"Invalid CyberGym runner image reference in {path}")
        if len(manifest.auth_token) < 16:
            raise ValueError(f"CyberGym auth token in {path} must contain at least 16 characters")
        return manifest


class CyberGymDockerEnvironment(DockerEnvironment):
    """Docker backend with optional in-process execution for a Compose lab service."""

    def __init__(
        self,
        environment_dir: Path,
        environment_name: str,
        session_id: str,
        trial_paths: TrialPaths,
        task_env_config: EnvironmentConfig,
        cybergym_local_execution: bool | str = False,
        cybergym_external_task_server_url: str | None = None,
        *args,
        **kwargs,
    ) -> None:
        self._compose_prefix: list[str] | None = None
        self._local_execution = self._parse_boolean(cybergym_local_execution, "cybergym_local_execution")
        self._external_task_server_url = self._resolve_external_task_server_url(
            cybergym_external_task_server_url,
            environment_dir=environment_dir,
            environment_name=environment_name,
        )
        if self._local_execution and not self._external_task_server_url:
            raise ValueError("cybergym_external_task_server_url is required for CyberGym local execution")
        self._task_server_auth_token = (
            "" if self._local_execution else self._load_task_server_auth_token(environment_dir)
        )

        self._local_root = (trial_paths.trial_dir / LOCAL_ENVIRONMENT_DIRNAME).resolve()
        self._local_workspace = self._local_root / "workspace"
        self._local_tests = self._local_root / "tests"
        tmux_dir_key = hashlib.sha256(f"{trial_paths.trial_dir.resolve()}\0{session_id}".encode()).hexdigest()[:16]
        # tmux appends /tmux-<uid>/default to TMUX_TMPDIR, and Unix-domain
        # sockets are limited to roughly 108 bytes on Linux. Harbor trial paths
        # are often already longer than that, so keep only the socket under a
        # short, per-trial /tmp path. Workspaces and artifacts stay in the
        # configured Harbor jobs directory.
        self._local_tmux_dir = LOCAL_TMUX_ROOT / tmux_dir_key
        self._local_agent_logs = trial_paths.agent_dir.resolve()
        self._local_verifier_logs = trial_paths.verifier_dir.resolve()

        trial_paths.trial_dir.mkdir(parents=True, exist_ok=True)
        self._runtime_compose_path = trial_paths.trial_dir / RUNTIME_COMPOSE_FILENAME
        if not self._local_execution:
            self._runtime_compose_path.write_text(RUNTIME_DOCKER_COMPOSE, encoding="utf-8")
        super().__init__(
            environment_dir=environment_dir,
            environment_name=environment_name,
            session_id=session_id,
            trial_paths=trial_paths,
            task_env_config=task_env_config,
            *args,
            **kwargs,
        )

    @property
    def cybergym_local_execution(self) -> bool:
        """Whether Harbor commands execute directly in the evaluator container."""
        return self._local_execution

    @staticmethod
    def _parse_boolean(value: bool | str, name: str) -> bool:
        if isinstance(value, bool):
            return value
        normalized = value.strip().lower()
        if normalized in {"1", "true", "yes", "on"}:
            return True
        if normalized in {"0", "false", "no", "off", ""}:
            return False
        raise ValueError(f"{name} must be a boolean, got {value!r}")

    @staticmethod
    def _resolve_external_task_server_url(
        raw_url: str | None,
        *,
        environment_dir: Path,
        environment_name: str,
    ) -> str:
        if not raw_url or not raw_url.strip():
            return ""
        task_name = environment_dir.parent.name
        runner_service = task_name.removeprefix("cybergym_") + "_vul"
        try:
            url = (
                raw_url.strip()
                .format(
                    task_name=task_name,
                    environment_name=environment_name,
                    runner_service=runner_service,
                )
                .rstrip("/")
            )
        except (IndexError, KeyError, ValueError) as error:
            raise ValueError(
                "CYBERGYM_EXTERNAL_TASK_SERVER_URL supports only the {task_name}, "
                "{environment_name}, and {runner_service} placeholders"
            ) from error
        parsed = urlsplit(url)
        if parsed.scheme not in {"http", "https"} or not parsed.netloc or parsed.query or parsed.fragment:
            raise ValueError(f"Invalid CyberGym external task-server URL: {url!r}")
        return url

    @staticmethod
    def _load_task_server_auth_token(environment_dir: Path) -> str:
        compose_path = environment_dir / "docker-compose.yaml"
        if not compose_path.is_file():
            raise FileNotFoundError(
                f"CyberGym Docker compose file is missing: {compose_path}. "
                "Re-run gym eval prepare --benchmark cybergym."
            )

        compose = compose_path.read_text(encoding="utf-8")
        match = re.search(r"(?m)^\s*-\s*AUTH_TOKEN=([^\s#]+)\s*$", compose)
        if match is None:
            raise ValueError(
                f"CyberGym task-server auth token is missing from {compose_path}. "
                "Re-run gym eval prepare --benchmark cybergym."
            )

        token = match.group(1).strip().strip("'\"")
        if not TASK_SERVER_AUTH_TOKEN_PATTERN.fullmatch(token):
            raise ValueError(f"CyberGym task-server auth token in {compose_path} is invalid")
        return token

    @property
    def _docker_compose_path(self) -> Path:
        # Do not execute generated task topology directly. Older prepared task
        # trees may still request one or two user-defined bridge networks, and
        # some cluster Docker daemons have no allocatable default address pool.
        return self._runtime_compose_path

    def _compose_environment(self) -> dict[str, str]:
        environment = self._env_vars.to_env_dict(include_os_env=True)
        requested_mode = environment.get("CYBERGYM_NETWORK_MODE", "").strip().lower()
        if requested_mode:
            if requested_mode not in {"public", "restricted"}:
                raise ValueError(
                    f"CYBERGYM_NETWORK_MODE must be either 'public' or 'restricted', got {requested_mode!r}"
                )
            network_mode = "bridge" if requested_mode == "public" else "none"
        else:
            # DockerEnvironment derives this from task_env_config.allow_internet.
            network_mode = environment.get("NETWORK_MODE", "none").strip().lower()

        if network_mode not in {"bridge", "none"}:
            raise ValueError(f"Unsupported Harbor Docker NETWORK_MODE: {network_mode!r}")

        # Both values select Docker's existing built-in networks. The main
        # service shares this namespace, so no per-trial subnet is allocated.
        environment["NETWORK_MODE"] = network_mode
        environment[TASK_SERVER_AUTH_TOKEN_ENV] = self._task_server_auth_token
        return environment

    async def _resolve_compose_prefix(self) -> list[str]:
        if self._compose_prefix is not None:
            return self._compose_prefix

        candidates: list[list[str]] = []
        docker = shutil.which("docker")
        if docker is not None:
            candidates.append([docker, "compose"])
        docker_compose = shutil.which("docker-compose")
        if docker_compose is not None:
            candidates.append([docker_compose])

        diagnostics = []
        for prefix in candidates:
            process = await asyncio.create_subprocess_exec(
                *prefix,
                "version",
                stdin=asyncio.subprocess.DEVNULL,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.STDOUT,
            )
            try:
                output, _ = await process.communicate()
            except BaseException:
                await self._terminate_subprocess(process)
                raise
            if process.returncode == 0:
                self._compose_prefix = prefix
                return prefix
            diagnostics.append(f"{' '.join(prefix)}: {output.decode(errors='replace').strip()[-1000:]}")

        diagnostic_text = "; ".join(diagnostics) if diagnostics else "no Docker Compose command was found"
        raise RuntimeError(
            "CyberGym's Docker backend requires Docker Compose. Install the Docker Compose v2 plugin "
            "(`docker compose version` must succeed), install the legacy `docker-compose` command, or use "
            "benchmarks/cybergym/config_apptainer.yaml. Detection details: "
            f"{diagnostic_text}"
        )

    async def _run_docker_compose_command(
        self, command: list[str], check: bool = True, timeout_sec: int | None = None
    ) -> ExecResult:
        compose_prefix = await self._resolve_compose_prefix()
        full_command = [
            *compose_prefix,
            "-p",
            self.session_id.lower().replace(".", "-"),
            "-f",
            str(self._docker_compose_path.resolve().absolute()),
            *command,
        ]
        process = await asyncio.create_subprocess_exec(
            *full_command,
            env=self._compose_environment(),
            stdin=asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT,
        )
        try:
            if timeout_sec:
                output, _ = await asyncio.wait_for(process.communicate(), timeout=timeout_sec)
            else:
                output, _ = await process.communicate()
        except asyncio.TimeoutError:
            process.terminate()
            try:
                await asyncio.wait_for(process.communicate(), timeout=5)
            except asyncio.TimeoutError:
                process.kill()
                await process.communicate()
            raise RuntimeError(f"Docker Compose command timed out after {timeout_sec} seconds") from None

        decoded_output = output.decode(errors="replace") if output else None
        return_code = process.returncode or 0
        result = ExecResult(
            stdout=decoded_output,
            # The pinned Docker backend combines both streams. Preserve the
            # combined output as stderr on failure so callers such as Harbor's
            # tmux setup do not report the unhelpful `Error: None`.
            stderr=decoded_output if return_code != 0 else None,
            return_code=return_code,
        )
        if check and result.return_code != 0:
            raise RuntimeError(
                f"Docker Compose command failed for environment {self.environment_name}. "
                f"Command: {' '.join(full_command)}. Return code: {result.return_code}. Output: {result.stdout}"
            )
        return result

    def _local_path(self, path: str | Path) -> Path:
        raw_path = str(path)
        mappings = (
            ("/logs/verifier", self._local_verifier_logs),
            ("/logs/agent", self._local_agent_logs),
            ("/workspace", self._local_workspace),
            ("/tests", self._local_tests),
        )
        for remote_prefix, local_prefix in mappings:
            if raw_path == remote_prefix:
                return local_prefix
            if raw_path.startswith(remote_prefix + "/"):
                return local_prefix / raw_path[len(remote_prefix) + 1 :]
        return Path(raw_path)

    def _local_command(self, command: str) -> str:
        mappings = (
            ("/logs/verifier", self._local_verifier_logs),
            ("/logs/agent", self._local_agent_logs),
            ("/workspace", self._local_workspace),
            ("/tests", self._local_tests),
        )
        for remote_prefix, local_prefix in mappings:
            command = command.replace(remote_prefix, str(local_prefix))
        return command

    def _local_child_environment(self, extra_env: dict[str, str] | None = None) -> dict[str, str]:
        child_env = os.environ.copy()
        for key in tuple(child_env):
            normalized = key.upper()
            if any(marker in normalized for marker in ("_API_KEY", "_TOKEN", "PASSWORD", "SECRET", "CREDENTIAL")):
                child_env.pop(key)
        child_env["CYBERGYM_TASK_SERVER_URL"] = self._external_task_server_url
        child_env["CYBERGYM_WORKSPACE_DIR"] = str(self._local_workspace)
        child_env["CYBERGYM_TESTS_DIR"] = str(self._local_tests)
        child_env["CYBERGYM_AGENT_LOGS_DIR"] = str(self._local_agent_logs)
        child_env["CYBERGYM_VERIFIER_LOGS_DIR"] = str(self._local_verifier_logs)
        for key, value in (extra_env or {}).items():
            if not ENVIRONMENT_VARIABLE_PATTERN.fullmatch(key):
                raise ValueError(f"Invalid environment variable name: {key!r}")
            child_env[key] = value
        # A lab terminal may itself be running inside tmux. Harbor needs a
        # separate server per trial, selected by TMUX_TMPDIR below; inheriting
        # TMUX would instead reconnect every trial to the lab terminal's server.
        child_env.pop("TMUX", None)
        child_env.pop("TMUX_PANE", None)
        child_env["TMUX_TMPDIR"] = str(self._local_tmux_dir)
        return child_env

    def _prepare_local_workspace_sync(self) -> None:
        if self._local_root.exists():
            shutil.rmtree(self._local_root)
        if self._local_tmux_dir.exists():
            shutil.rmtree(self._local_tmux_dir)
        self._local_workspace.mkdir(parents=True)
        self._local_tests.mkdir()
        self._local_tmux_dir.mkdir(mode=0o700, parents=True)

        submit_script = self.environment_dir / "submit.sh"
        if not submit_script.is_file():
            raise FileNotFoundError(
                f"CyberGym submission helper is missing: {submit_script}. "
                "Re-run `gym eval prepare --benchmark cybergym`."
            )
        shutil.copy2(submit_script, self._local_workspace / "submit.sh")

        task_data = self.environment_dir / "task_data"
        if not task_data.is_dir() or not any(path.is_file() for path in task_data.iterdir()):
            raise FileNotFoundError(
                f"CyberGym local task data is missing from {task_data}. Re-run preparation with "
                "`benchmarks/cybergym/prepare.py --download-task-data`."
            )
        shutil.copytree(task_data, self._local_workspace / "task_data")

    async def _local_exec(
        self,
        command: str,
        cwd: str | None,
        env: dict[str, str] | None,
        timeout_sec: int | None,
    ) -> ExecResult:
        local_command = self._local_command(command)
        local_cwd = self._local_path(cwd) if cwd else self._local_workspace
        # A detached child such as tmux can retain a subprocess pipe after the
        # shell exits, causing Process.communicate() to wait forever for EOF.
        # A regular file preserves command output without coupling completion
        # to the lifetime of descendant file descriptors.
        with tempfile.TemporaryFile() as output_file:
            process = await asyncio.create_subprocess_exec(
                "/bin/bash",
                # Terminal interaction happens inside Harbor's tmux session;
                # this outer command runner must remain noninteractive.
                "-c",
                local_command,
                cwd=str(local_cwd),
                env=self._local_child_environment(env),
                stdin=asyncio.subprocess.DEVNULL,
                stdout=output_file,
                stderr=asyncio.subprocess.STDOUT,
                start_new_session=True,
            )
            try:
                if timeout_sec:
                    await asyncio.wait_for(process.wait(), timeout=timeout_sec)
                else:
                    await process.wait()
            except asyncio.TimeoutError:
                try:
                    os.killpg(process.pid, signal.SIGTERM)
                except ProcessLookupError:
                    pass
                try:
                    await asyncio.wait_for(process.wait(), timeout=5)
                except asyncio.TimeoutError:
                    try:
                        os.killpg(process.pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
                    await process.wait()
                output = os.pread(output_file.fileno(), os.fstat(output_file.fileno()).st_size, 0)
                decoded = output.decode(errors="replace") if output else ""
                decoded += f"\nCommand timed out after {timeout_sec} seconds"
                return ExecResult(stdout=decoded, stderr=decoded, return_code=124)

            output = os.pread(output_file.fileno(), os.fstat(output_file.fileno()).st_size, 0)

        decoded = output.decode(errors="replace") if output else None
        return_code = process.returncode or 0
        return ExecResult(
            stdout=decoded,
            stderr=decoded if return_code != 0 else None,
            return_code=return_code,
        )

    async def exec(
        self,
        command: str,
        cwd: str | None = None,
        env: dict[str, str] | None = None,
        timeout_sec: int | None = None,
    ) -> ExecResult:
        if self._local_execution:
            return await self._local_exec(command, cwd, env, timeout_sec)

        # Harbor launches commands with stdin=/dev/null. Disable Compose's
        # outer pseudo-TTY; pinned Terminus-2 creates the PTY it needs with the
        # `script` command inside the container.
        exec_command = ["exec", "-T"]
        if cwd:
            exec_command.extend(["-w", cwd])
        if env:
            for key, value in env.items():
                exec_command.extend(["-e", f"{key}={shlex.quote(value)}"])
        exec_command.extend(["main", "bash", "-ic", command])
        return await self._run_docker_compose_command(
            exec_command,
            check=False,
            timeout_sec=timeout_sec,
        )

    async def start(self, force_build: bool) -> None:
        if self._local_execution:
            if force_build:
                self.logger.warning("force_build has no effect when CyberGym executes in the current lab container")
            await asyncio.to_thread(self._prepare_local_workspace_sync)
            preflight_command = (
                "command -v tmux && command -v script && command -v curl && tmux -V && "
                'curl -fsS --max-time 10 "$CYBERGYM_TASK_SERVER_URL/health" >/dev/null'
            )
        else:
            await super().start(force_build=force_build)
            preflight_command = "command -v tmux && command -v script && tmux -V"

        terminal_preflight = await self.exec(preflight_command)
        if terminal_preflight.return_code != 0:
            detail = terminal_preflight.stderr or terminal_preflight.stdout or "<no command output>"
            if self._local_execution:
                raise RuntimeError(
                    "The Automodel lab container failed CyberGym's local tmux/PTY or ARVO service health "
                    "preflight. Check that tmux, script, and curl are installed; the task was prepared with "
                    "--download-task-data; and CYBERGYM_EXTERNAL_TASK_SERVER_URL resolves on the Compose network. "
                    f"Lab output: {detail}"
                )
            normalized_detail = detail.lower()
            if "not running" in normalized_detail or "no container found" in normalized_detail:
                diagnostics = await self._main_container_diagnostics()
                raise RuntimeError(
                    "CyberGym main container exited before the tmux/PTY preflight. "
                    "This is a container lifecycle failure, not evidence that tmux is missing.\n"
                    f"Compose exec output:\n{detail}\n{diagnostics}"
                )
            raise RuntimeError(
                "CyberGym agent image failed its tmux/PTY preflight. Re-run "
                "`gym eval prepare --benchmark cybergym` so the image includes "
                f"tmux and bsdutils. Container output: {detail}"
            )

    async def stop(self, delete: bool) -> None:
        if self._local_execution:
            if not self._local_root.exists() and not self._local_tmux_dir.exists():
                return
            try:
                if self._local_tmux_dir.exists():
                    await self._local_exec("tmux kill-server", None, None, 30)
            finally:
                await asyncio.to_thread(shutil.rmtree, self._local_root, True)
                await asyncio.to_thread(shutil.rmtree, self._local_tmux_dir, True)
            return
        await super().stop(delete=delete)

    async def upload_file(self, source_path: Path | str, target_path: str) -> None:
        if self._local_execution:
            source = Path(source_path)
            target = self._local_path(target_path)
            if not source.is_file():
                raise FileNotFoundError(f"CyberGym upload source file does not exist: {source}")
            await asyncio.to_thread(target.parent.mkdir, parents=True, exist_ok=True)
            await asyncio.to_thread(shutil.copy2, source, target)
            return
        await super().upload_file(source_path, target_path)

    async def upload_dir(self, source_dir: Path | str, target_dir: str) -> None:
        if self._local_execution:
            source = Path(source_dir)
            target = self._local_path(target_dir)
            if not source.is_dir():
                raise FileNotFoundError(f"CyberGym upload source directory does not exist: {source}")
            if target.exists():
                await asyncio.to_thread(shutil.rmtree, target)
            await asyncio.to_thread(shutil.copytree, source, target)
            return
        await super().upload_dir(source_dir, target_dir)

    async def download_file(self, source_path: str, target_path: Path | str) -> None:
        if self._local_execution:
            source = self._local_path(source_path)
            target = Path(target_path)
            if target.is_dir():
                target = target / source.name
            if not source.is_file():
                raise FileNotFoundError(f"CyberGym download source file does not exist: {source}")
            await asyncio.to_thread(target.parent.mkdir, parents=True, exist_ok=True)
            await asyncio.to_thread(shutil.copy2, source, target)
            return
        await super().download_file(source_path, target_path)

    async def download_dir(self, source_dir: str, target_dir: Path | str) -> None:
        if self._local_execution:
            source = self._local_path(source_dir)
            target = Path(target_dir)
            if not source.is_dir():
                raise FileNotFoundError(f"CyberGym download source directory does not exist: {source}")
            await asyncio.to_thread(target.mkdir, parents=True, exist_ok=True)
            await asyncio.to_thread(shutil.copytree, source, target, dirs_exist_ok=True)
            return
        await super().download_dir(source_dir, target_dir)

    async def _main_container_diagnostics(self) -> str:
        sections: list[str] = []
        for label, command in (
            ("Compose service status", ["ps", "-a"]),
            ("Main container logs", ["logs", "--no-color", "--tail", "200", "main"]),
        ):
            try:
                result = await self._run_docker_compose_command(
                    command,
                    check=False,
                    timeout_sec=30,
                )
                output = result.stdout or result.stderr or "<no output>"
            except Exception as error:
                output = f"<diagnostic command failed: {error}>"
            sections.append(f"{label}:\n{output}")
        return "\n".join(sections)


class CyberGymApptainerEnvironment(SingularityEnvironment):
    """Run the agent in a stripped SIF and verification in private runner SIFs."""

    def __init__(
        self,
        environment_dir: Path,
        environment_name: str,
        session_id: str,
        trial_paths: TrialPaths,
        task_env_config: EnvironmentConfig,
        cybergym_agent_sif: str | Path | None = None,
        cybergym_runner_timeout_sec: int = 10,
        cybergym_max_poc_bytes: int = 10 * 1024 * 1024,
        cybergym_max_output_bytes: int = 1024 * 1024,
        cybergym_fakeroot: bool | None = None,
        *args,
        **kwargs,
    ) -> None:
        self._manifest_path = environment_dir / MANIFEST_FILENAME
        self._definition_path = environment_dir / AGENT_DEFINITION_FILENAME
        self._manifest = CyberGymApptainerManifest.load(self._manifest_path)
        self._prebuilt_agent_sif = str(cybergym_agent_sif) if cybergym_agent_sif else None
        self._runner_timeout_sec = cybergym_runner_timeout_sec
        self._max_poc_bytes = cybergym_max_poc_bytes
        self._max_output_bytes = cybergym_max_output_bytes
        self._cybergym_fakeroot = cybergym_fakeroot
        self._task_server: CyberGymTaskServer | None = None
        self._task_server_url: str | None = None

        super().__init__(
            environment_dir=environment_dir,
            environment_name=environment_name,
            session_id=session_id,
            trial_paths=trial_paths,
            task_env_config=task_env_config,
            *args,
            **kwargs,
        )

    def _validate_definition(self) -> None:
        if not self._definition_path.is_file():
            raise FileNotFoundError(
                f"CyberGym agent definition is missing: {self._definition_path}. "
                "Re-run `gym eval prepare --benchmark cybergym`."
            )
        if self._runner_timeout_sec <= 0 or self._max_poc_bytes <= 0 or self._max_output_bytes <= 0:
            raise ValueError("CyberGym Apptainer resource limits must be positive")

    @staticmethod
    def _find_host_python_mounts() -> list[tuple[str, str]]:
        # Generated CyberGym SIFs contain /opt/harbor-runtime. Keeping host
        # interpreters out avoids glibc mismatches and reduces host exposure.
        return []

    def _container_environment(self) -> dict[str, str]:
        if self._task_server_url is None:
            raise RuntimeError("CyberGym task server URL is unavailable")
        return {"CYBERGYM_TASK_SERVER_URL": self._task_server_url}

    def _runtime_fakeroot_args(self) -> list[str]:
        # Executing a prebuilt SIF does not inherently require fakeroot. Keep
        # it opt-in at runtime so clusters that prohibit user namespaces can
        # use prebuilt agent SIFs; automatic definition builds still default to
        # fakeroot for non-root users below.
        return ["--fakeroot"] if self._cybergym_fakeroot is True else []

    def _agent_image_digest(self) -> str:
        digest = hashlib.sha256()
        for path in [self._definition_path, self.environment_dir / "submit.sh"]:
            digest.update(path.name.encode())
            digest.update(path.read_bytes())
        task_data_dir = self.environment_dir / "task_data"
        if task_data_dir.is_dir():
            for path in sorted(candidate for candidate in task_data_dir.rglob("*") if candidate.is_file()):
                digest.update(path.relative_to(task_data_dir).as_posix().encode())
                digest.update(path.read_bytes())
        return digest.hexdigest()

    def _configured_agent_sif(self) -> Path | None:
        if self._prebuilt_agent_sif is None:
            return None
        task_name = self.environment_dir.parent.name
        rendered = self._prebuilt_agent_sif.format(task_name=task_name, raw_task_name=self.environment_name)
        path = Path(rendered).expanduser().resolve()
        if not path.is_file():
            raise FileNotFoundError(f"Configured CyberGym agent SIF does not exist: {path}")
        return path

    async def _build_agent_sif(self, vulnerable_sif: Path) -> Path:
        configured = self._configured_agent_sif()
        if configured is not None:
            return configured

        self._image_cache_dir.mkdir(parents=True, exist_ok=True)
        safe_name = re.sub(r"[^A-Za-z0-9_.-]+", "_", self.environment_dir.parent.name)
        digest = self._agent_image_digest()[:20]
        sif_path = self._image_cache_dir / f"cybergym_agent_{safe_name}_{digest}.sif"
        lock_path = sif_path.with_suffix(".sif.lock")
        if not self._force_pull and sif_path.is_file():
            return sif_path

        lock_file = lock_path.open("w")
        temporary_sif = sif_path.with_suffix(f".sif.tmp.{self.session_id}")
        temporary_definition = sif_path.with_suffix(f".def.tmp.{self.session_id}")
        try:
            loop = asyncio.get_running_loop()
            await loop.run_in_executor(None, lambda: fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX))
            if self._force_pull and sif_path.exists():
                sif_path.unlink()
            if sif_path.is_file():
                return sif_path

            definition = self._definition_path.read_text(encoding="utf-8")
            expected_from = f"From: {self._manifest.vulnerable_image}"
            if "Bootstrap: docker" not in definition or expected_from not in definition:
                raise ValueError(
                    f"{self._definition_path} does not use the vulnerable image declared in {self._manifest_path}"
                )
            definition = definition.replace("Bootstrap: docker", "Bootstrap: localimage", 1)
            definition = definition.replace(expected_from, f"From: {vulnerable_sif.resolve()}", 1)
            temporary_definition.write_text(definition, encoding="utf-8")

            temporary_sif.unlink(missing_ok=True)
            fakeroot = os.getuid() != 0 if self._cybergym_fakeroot is None else self._cybergym_fakeroot
            fakeroot_args = ["--fakeroot"] if fakeroot else []
            command = [
                self._singularity_executable,
                "build",
                *fakeroot_args,
                str(temporary_sif),
                str(temporary_definition),
            ]
            self.logger.info(f"Building CyberGym agent SIF: {sif_path}")
            process = await asyncio.create_subprocess_exec(
                *command,
                cwd=str(self.environment_dir),
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.STDOUT,
            )
            try:
                output, _ = await process.communicate()
            except BaseException:
                await self._terminate_subprocess(process)
                raise
            if process.returncode != 0:
                diagnostic = output.decode(errors="replace")[-12000:] if output else "<no output>"
                raise RuntimeError(f"Failed to build CyberGym agent SIF with {' '.join(command)}: {diagnostic}")
            temporary_sif.replace(sif_path)
            return sif_path
        finally:
            temporary_sif.unlink(missing_ok=True)
            temporary_definition.unlink(missing_ok=True)
            fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)
            lock_file.close()

    async def start(self, force_build: bool) -> None:
        if force_build:
            self._force_pull = True

        vulnerable_sif = await self._convert_docker_to_sif(self._manifest.vulnerable_image)
        fixed_sif = await self._convert_docker_to_sif(self._manifest.fixed_image)
        self._sif_path = await self._build_agent_sif(vulnerable_sif)

        runtime_fakeroot = self._cybergym_fakeroot is True
        runner = ApptainerRunner(
            executable=self._singularity_executable,
            task_type=self._manifest.task_type,
            vulnerable_sif=vulnerable_sif,
            fixed_sif=fixed_sif,
            timeout_sec=self._runner_timeout_sec,
            max_output_bytes=self._max_output_bytes,
            fakeroot=runtime_fakeroot,
        )
        self._task_server = CyberGymTaskServer(
            runner=runner,
            auth_token=self._manifest.auth_token,
            max_poc_bytes=self._max_poc_bytes,
        )
        await asyncio.to_thread(self._task_server.start)
        self._task_server_url = self._task_server.url
        try:
            await self._start_server()
        except BaseException:
            await asyncio.to_thread(self._task_server.stop)
            self._task_server = None
            self._task_server_url = None
            raise

    async def stop(self, delete: bool) -> None:
        try:
            await super().stop(delete=delete)
        finally:
            if self._task_server is not None:
                await asyncio.to_thread(self._task_server.stop)
                self._task_server = None
                self._task_server_url = None
